// Generates db/seed.sql from the mock data so D1 starts with the same demo content.
// Usage: npm run db:seed:generate
import { writeFileSync, mkdirSync } from 'node:fs'
import {
  mockUsers,
  mockProducts,
  mockStreams,
  mockCategories,
  mockCourses,
  mockAuctions,
  currentUser,
} from '../src/data/mock-data'

type Value = string | number | boolean | null | undefined

function sql(v: Value): string {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  if (typeof v === 'number') return String(v)
  return `'${v.replace(/'/g, "''")}'`
}

const cents = (reais?: number) => (reais === undefined ? null : Math.round(reais * 100))
const iso = (d?: Date | string) => (d === undefined ? null : new Date(d).toISOString())
const json = (v: unknown) => JSON.stringify(v ?? [])

const lines: string[] = []
function insert(table: string, row: Record<string, Value>) {
  const cols = Object.keys(row)
  lines.push(`INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map(c => sql(row[c])).join(', ')});`)
}

const sellerIds = new Set([
  ...mockProducts.map(p => p.seller.id),
  ...mockStreams.map(s => s.host.id),
  ...mockCourses.map(c => c.instructor.id),
])

for (const u of [...mockUsers, currentUser]) {
  insert('users', {
    id: u.id,
    name: u.name,
    username: u.username,
    avatar: u.avatar,
    bio: u.bio,
    is_verified: u.isVerified,
    is_seller: sellerIds.has(u.id),
    followers_count: u.followers,
    following_count: u.following,
  })
}

mockCategories.forEach((c, i) => {
  insert('categories', { id: c.id, slug: c.slug, name: c.name, icon: c.icon, color: c.color, sort_order: i })
})

for (const p of mockProducts) {
  insert('products', {
    id: p.id,
    seller_id: p.seller.id,
    category_slug: p.category,
    name: p.name,
    description: p.description,
    price_cents: cents(p.price),
    original_price_cents: cents(p.originalPrice),
    stock: p.stock,
    images: json(p.images),
    tags: json(p.tags),
    rating: p.rating,
    reviews_count: p.reviews,
  })
  p.variants?.forEach((v, i) => {
    insert('product_variants', {
      id: `${p.id}-${v.id}`,
      product_id: p.id,
      type: v.type,
      name: v.name,
      value: v.value,
      stock: v.stock,
      price_modifier_cents: cents(v.priceModifier ?? 0),
      sort_order: i,
    })
  })
}

for (const c of mockCourses) {
  insert('courses', {
    id: c.id,
    instructor_id: c.instructor.id,
    category_slug: c.category,
    name: c.name,
    description: c.description,
    price_cents: cents(c.price),
    original_price_cents: cents(c.originalPrice),
    thumbnail: c.thumbnail,
    tags: json(c.tags),
    rating: c.rating,
    reviews_count: c.reviews,
    duration: c.duration,
    lessons_count: c.lessonsCount,
    students_count: c.studentsCount,
    level: c.level,
    language: c.language,
    certificate_included: c.certificateIncluded,
    updated_at: iso(c.lastUpdated),
  })
  c.modules.forEach((m, i) => {
    insert('course_modules', { id: m.id, course_id: c.id, title: m.title, duration: m.duration, sort_order: i })
    m.lessons.forEach((l, j) => {
      insert('course_lessons', {
        id: l.id,
        module_id: m.id,
        title: l.title,
        duration: l.duration,
        is_free: l.isFree,
        type: l.type,
        sort_order: j,
      })
    })
  })
}

for (const s of mockStreams) {
  insert('streams', {
    id: s.id,
    host_id: s.host.id,
    category_slug: s.category,
    title: s.title,
    description: s.description,
    thumbnail: s.thumbnail,
    video_url: s.videoUrl,
    status: s.isLive ? 'live' : 'scheduled',
    scheduled_at: iso(s.scheduledTime),
    started_at: s.isLive ? iso(s.startTime) : null,
    viewer_count: s.viewerCount,
    likes: s.likes,
    tags: json(s.tags),
  })
  s.products.forEach((p, i) => {
    insert('stream_products', { stream_id: s.id, product_id: p.id, sort_order: i })
  })
}

for (const a of mockAuctions) {
  insert('auctions', {
    id: a.id,
    product_id: a.product.id,
    stream_id: a.streamId,
    starting_price_cents: cents(a.startingPrice),
    current_bid_cents: cents(a.currentBid),
    minimum_increment_cents: cents(a.minimumIncrement),
    starts_at: iso(a.startTime),
    ends_at: iso(a.endTime),
    status: a.status,
    winner_id: a.winnerId,
  })
  for (const b of a.bids) {
    insert('bids', {
      id: b.id,
      auction_id: a.id,
      user_id: b.user.id,
      amount_cents: cents(b.amount),
      created_at: iso(b.timestamp),
    })
  }
}

mkdirSync('db', { recursive: true })
writeFileSync('db/seed.sql', `-- Generated by scripts/generate-seed.ts. Do not edit by hand.\n${lines.join('\n')}\n`)
console.log(`Wrote db/seed.sql (${lines.length} rows)`)
